#!/usr/bin/env python3
"""Builder egress generator (R20-6, issue #1022). Stdlib only.

Reads allowlist.txt and renders four files for the builder uid:
  roxira_builder.nft      nftables table: the builder uid may only reach loopback ports from the allowlist
  tinyproxy.conf          allowlist proxy in front of xray (upstream = the box proxy)
  tinyproxy.filter        host filter, default deny
  builder-proxy.env       HTTPS_PROXY etc. for the builder's shell/unit (no secret)

Dry run is the default: it prints a unified diff against the files already in --out-dir (nothing is written).
--write writes the files into --out-dir. This script never touches /etc, nft, sudoers or xray: the owner
copies the files (docs/ops/BUILDER_EGRESS.md).
"""
from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HOST_RE = re.compile(r"^(?:\*\.)?(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$")
USER_RE = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
PROXY_PORT_DEFAULT = 10810
UPSTREAM_DEFAULT = ("127.0.0.1", 10809)


class AllowlistError(ValueError):
    pass


def parse_allowlist(text: str) -> tuple[list[str], list[int]]:
    domains: list[str] = []
    ports: list[int] = []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip().lower()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2:
            raise AllowlistError(f"line {n}: expected '<kind> <value>'")
        kind, value = parts
        if kind == "domain":
            if not HOST_RE.match(value):
                raise AllowlistError(f"line {n}: bad domain {value!r}")
            if value.startswith("*.") and value.count(".") < 2:
                raise AllowlistError(f"line {n}: wildcard on a bare TLD {value!r}")
            if value not in domains:
                domains.append(value)
        elif kind == "port":
            if not value.isdigit() or not 1 <= int(value) <= 65535:
                raise AllowlistError(f"line {n}: bad port {value!r}")
            if int(value) not in ports:
                ports.append(int(value))
        else:
            raise AllowlistError(f"line {n}: unknown kind {kind!r}")
    if not domains and not ports:
        raise AllowlistError("allowlist is empty")
    return domains, ports


def render_nft(user: str, ports: list[int]) -> str:
    if not USER_RE.match(user):
        raise AllowlistError(f"bad user name {user!r}")
    plist = ", ".join(str(p) for p in sorted(ports))
    return f"""#!/usr/sbin/nft -f
# GENERATED by gen_egress.py from allowlist.txt. Do not edit by hand.
# Network limits for the builder uid only. Remove with: nft delete table inet roxira_builder
table inet roxira_builder
delete table inet roxira_builder

table inet roxira_builder {{
  chain output {{
    type filter hook output priority -200; policy accept;
    # Positive uid match on purpose (see agent_egress.nft): kernel packets have no socket.
    meta skuid "{user}" jump builder
  }}

  chain builder {{
    ct state established,related accept
    oif "lo" ip daddr 127.0.0.1 tcp dport {{ {plist} }} accept
    oif "lo" ip6 daddr ::1 tcp dport {{ {plist} }} accept
    counter reject
  }}
}}
"""


def domain_regex(d: str) -> str:
    if d.startswith("*."):
        return r"^(.+\.)?" + re.escape(d[2:]) + "$"
    return "^" + re.escape(d) + "$"


def render_filter(domains: list[str]) -> str:
    head = "# GENERATED by gen_egress.py from allowlist.txt. Extended regex, one host per line, default deny.\n"
    return head + "".join(domain_regex(d) + "\n" for d in domains)


def render_proxy_conf(port: int, upstream: tuple[str, int], filter_path: str) -> str:
    return f"""# GENERATED by gen_egress.py from allowlist.txt. Do not edit by hand.
Port {port}
Listen 127.0.0.1
Timeout 60
MaxClients 20
Allow 127.0.0.1
# Only the allowlisted hosts, only TLS.
Filter "{filter_path}"
FilterType ere
FilterDefaultDeny Yes
ConnectPort 443
DisableViaHeader Yes
# Out through the always-on box proxy (xray HTTP inbound).
Upstream http {upstream[0]}:{upstream[1]}
LogLevel Info
"""


def render_env(port: int) -> str:
    return (
        "# GENERATED by gen_egress.py. Source for the builder user only. Contains no secret.\n"
        f"HTTP_PROXY=http://127.0.0.1:{port}\nHTTPS_PROXY=http://127.0.0.1:{port}\n"
        f"http_proxy=http://127.0.0.1:{port}\nhttps_proxy=http://127.0.0.1:{port}\n"
        "NO_PROXY=127.0.0.1,localhost\nNODE_USE_ENV_PROXY=1\n"
        "NPM_CONFIG_IGNORE_SCRIPTS=true\n"
    )


def render_all(text: str, user: str, proxy_port: int, upstream: tuple[str, int], filter_path: str) -> dict[str, str]:
    domains, ports = parse_allowlist(text)
    if proxy_port not in ports:
        raise AllowlistError(f"proxy port {proxy_port} must be listed as 'port' in the allowlist")
    if proxy_port == upstream[1]:
        raise AllowlistError("proxy port equals the upstream xray port")
    if upstream[1] in ports:
        raise AllowlistError("the xray port must not be reachable by builders")
    return {
        "roxira_builder.nft": render_nft(user, ports),
        "tinyproxy.filter": render_filter(domains),
        "tinyproxy.conf": render_proxy_conf(proxy_port, upstream, filter_path),
        "builder-proxy.env": render_env(proxy_port),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--allowlist", type=Path, default=HERE / "allowlist.txt")
    ap.add_argument("--out-dir", type=Path, default=HERE / "generated")
    ap.add_argument("--user", default="roxira-builder")
    ap.add_argument("--proxy-port", type=int, default=PROXY_PORT_DEFAULT)
    ap.add_argument("--upstream-port", type=int, default=UPSTREAM_DEFAULT[1])
    ap.add_argument("--filter-path", default="/etc/tinyproxy/roxira-builder.filter")
    ap.add_argument("--write", action="store_true", help="write the files into --out-dir (default: dry run, print diff)")
    a = ap.parse_args(argv)
    try:
        files = render_all(a.allowlist.read_text(), a.user, a.proxy_port,
                           (UPSTREAM_DEFAULT[0], a.upstream_port), a.filter_path)
    except (AllowlistError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    changed = False
    for name, new in files.items():
        path = a.out_dir / name
        old = path.read_text() if path.exists() else ""
        if old != new:
            changed = True
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), new.splitlines(True), f"a/{name}", f"b/{name}"))
            if a.write:
                a.out_dir.mkdir(parents=True, exist_ok=True)
                path.write_text(new)
    if not changed:
        print("no changes")
    elif not a.write:
        print("\n(dry run: nothing written; add --write)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
