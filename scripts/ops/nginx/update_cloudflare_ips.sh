#!/usr/bin/env bash
# Regenerate the nginx real-IP include from Cloudflare's published ranges.
#   scripts/ops/nginx/update_cloudflare_ips.sh [--reload]
# Writes nginx/generated/cloudflare_real_ip.conf (gitignored; mounted at
# /etc/nginx/cloudflare/generated). The file holds ONLY set_real_ip_from lines;
# the client-IP header directives are declared once in nginx.conf.
# The committed baseline nginx/cloudflare_params.conf stays in place, so a
# failed refresh never leaves nginx without trusted proxies.
#
# Safety: the new file is written to a temp file in the SAME directory and moved
# into place with an atomic rename (nginx never reads a half-written include).
# It is only installed when the download parsed to a sane number of ranges.
# With --reload, nginx is reloaded only after `nginx -t` passes; if the test
# fails the previous include is restored (or removed) and nginx is NOT reloaded.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/../../.." && pwd)"
OUT_DIR="${CF_REALIP_DIR:-$ROOT/nginx/generated}"
OUT="$OUT_DIR/cloudflare_real_ip.conf"
NGINX_CONTAINER="${NGINX_CONTAINER:-roxira_nginx_prod}"
MIN_V4="${CF_MIN_V4:-10}"
MIN_V6="${CF_MIN_V6:-5}"
RELOAD=0
[[ "${1:-}" == "--reload" ]] && RELOAD=1

mkdir -p "$OUT_DIR"
tmp="$(mktemp "$OUT_DIR/.cloudflare_real_ip.XXXXXX")"
prev=""
# shellcheck disable=SC2329  # invoked via trap
cleanup() { rm -f "$tmp"; [[ -n "$prev" ]] && rm -f "$prev"; return 0; }
trap cleanup EXIT

v4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"

n4=0; n6=0
{
  echo "# Generated by scripts/ops/nginx/update_cloudflare_ips.sh on $(date -u +%FT%TZ)"
  echo "# Do not edit; do not commit."
} >"$tmp"
for r in $v4; do
  if [[ "$r" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]|[12][0-9]|3[0-2])$ ]]; then
    echo "set_real_ip_from $r;" >>"$tmp"; n4=$((n4 + 1))
  fi
done
for r in $v6; do
  if [[ "$r" =~ ^[0-9a-fA-F:]+:[0-9a-fA-F:]*/([0-9]|[1-9][0-9]|1[01][0-9]|12[0-8])$ ]]; then
    echo "set_real_ip_from $r;" >>"$tmp"; n6=$((n6 + 1))
  fi
done

if (( n4 < MIN_V4 || n6 < MIN_V6 )); then
  echo "refusing to install: parsed $n4 IPv4 (need $MIN_V4) and $n6 IPv6 (need $MIN_V6) ranges" >&2
  exit 1
fi

if [[ -f "$OUT" ]]; then
  prev="$(mktemp "$OUT_DIR/.cloudflare_real_ip.prev.XXXXXX")"
  cp -p "$OUT" "$prev"
fi
chmod 644 "$tmp"
mv -f "$tmp" "$OUT"   # atomic: same directory, same filesystem
echo "wrote $OUT ($n4 IPv4 + $n6 IPv6 ranges)"

if (( RELOAD )); then
  if docker exec "$NGINX_CONTAINER" nginx -t; then
    docker exec "$NGINX_CONTAINER" nginx -s reload
    echo "nginx reloaded"
  else
    echo "nginx -t failed; restoring previous include, NOT reloading" >&2
    if [[ -n "$prev" ]]; then mv -f "$prev" "$OUT"; prev=""; else rm -f "$OUT"; fi
    exit 1
  fi
fi
exit 0
