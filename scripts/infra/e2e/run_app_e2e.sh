#!/usr/bin/env bash
# Gate 3: run the browser E2E suite of the business app (/app/*) against a sandbox built from a git ref.
#
#   run_app_e2e.sh <git-ref>
#
# sandbox_up -> install Playwright browsers if missing (chromium + webkit; with OS deps when root on Linux) ->
# run e2e/playwright.app.config.ts (Chromium AND WebKit) -> sandbox_down. The last line is always
#   APP_E2E RESULT: PASS      (exit 0)   or   APP_E2E RESULT: FAIL   (exit 1)
# The HTML report and traces are left in e2e/app-report and e2e/app-results.
#
# Environment (all optional; the sandbox_up.sh variables apply too):
#   RX_E2E_KEEP=1        leave the sandbox running afterwards (debugging); remove with sandbox_down.sh
#   RX_E2E_WITH_DEPS     1/0: pass --with-deps to `playwright install` (default: 1 on Linux as root, else 0)
#   RX_E2E_PW_ARGS       extra arguments for `playwright test` (e.g. "--project=webkit -g drop")
set -uo pipefail
# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

REF="${1:-}"
[ -n "$REF" ] || { echo "usage: run_app_e2e.sh <git-ref>" >&2; echo "APP_E2E RESULT: FAIL"; exit 2; }

TOOL_ROOT="$(cd "$E2E_DIR/../../.." && pwd)"
SUITE_DIR="$TOOL_ROOT/e2e"
RESULT=FAIL
umask 077
mkdir -p "$RX_WORK" && chmod 700 "$RX_WORK"

finish() {
  if [ "${RX_E2E_KEEP:-0}" != 1 ]; then "$E2E_DIR/sandbox_down.sh" >/dev/null 2>&1 || true; fi
  echo "APP_E2E RESULT: $RESULT"
  [ "$RESULT" = PASS ]
}
trap 'finish; exit $?' EXIT

fail() { rx_log "$*"; RESULT=FAIL; exit 1; }

command -v node >/dev/null 2>&1 || fail "node is required to run Playwright"
command -v npm >/dev/null 2>&1 || fail "npm is required to run Playwright"
[ -f "$SUITE_DIR/playwright.app.config.ts" ] || fail "missing $SUITE_DIR/playwright.app.config.ts"

rx_log "== sandbox_up $REF"
"$E2E_DIR/sandbox_up.sh" "$REF" >"$RX_WORK/up.log" 2>&1 || {
  tail -30 "$RX_WORK/up.log" >&2
  fail "sandbox_up failed (full log: $RX_WORK/up.log)"
}
tail -8 "$RX_WORK/up.log" >&2

# Generated by sandbox_up.sh; contains paths and the base URL only (no secrets).
set -a
# shellcheck disable=SC1091
source "$RX_OUT/app_e2e.env"
set +a

rx_log "== playwright setup"
cd "$SUITE_DIR" || fail "cannot cd to $SUITE_DIR"
if [ ! -x node_modules/.bin/playwright ]; then
  npm ci --no-audit --no-fund >"$RX_WORK/npm.log" 2>&1 || { tail -15 "$RX_WORK/npm.log" >&2; fail "npm ci failed in $SUITE_DIR"; }
fi
WITH_DEPS="${RX_E2E_WITH_DEPS:-}"
if [ -z "$WITH_DEPS" ]; then
  if [ "$(uname -s)" = Linux ] && [ "$(id -u)" = 0 ]; then WITH_DEPS=1; else WITH_DEPS=0; fi
fi
install_args=(install)
[ "$WITH_DEPS" = 1 ] && install_args+=(--with-deps)
install_args+=(chromium webkit)
npx playwright "${install_args[@]}" >"$RX_WORK/pw-install.log" 2>&1 ||
  { tail -15 "$RX_WORK/pw-install.log" >&2; fail "playwright browser install failed"; }

rx_log "== playwright test (chromium + webkit) against $APP_E2E_BASE_URL"
# shellcheck disable=SC2086  # RX_E2E_PW_ARGS is intentionally word-split
if npx playwright test -c playwright.app.config.ts ${RX_E2E_PW_ARGS:-}; then
  RESULT=PASS
else
  rx_log "playwright reported failures; report: $SUITE_DIR/app-report/index.html, traces: $SUITE_DIR/app-results"
  RESULT=FAIL
fi
[ "$RESULT" = PASS ]
