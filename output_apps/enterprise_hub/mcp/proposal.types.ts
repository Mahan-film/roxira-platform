/**
 * شیء «پیشنهاد» (proposal) که ابزارهای نوشتنی MCP برمی‌گردانند.
 *
 * ابزارهای propose هیچ نوشتنی انجام نمی‌دهند؛ فقط ورودی را اعتبارسنجی می‌کنند و
 * یک پیشنهاد قابل‌بازبینی به همراه هشدارها برمی‌گردانند. نوشتن واقعی تنها پس از
 * تأیید کاربر در UI و از طریق همان مسیرهای REST موجود انجام می‌شود
 * (human-in-the-loop).
 */
export interface Proposal<K extends string, P> {
  /** نوع پیشنهاد، مثلاً `crm.lead`. */
  kind: K;
  /** بارِ پیشنهادی که پس از تأیید به مسیر REST مالک ارسال می‌شود. */
  payload: P;
  /** هشدارهای غیرمسدودکننده (مثلاً رکورد تکراری). */
  warnings: string[];
}
