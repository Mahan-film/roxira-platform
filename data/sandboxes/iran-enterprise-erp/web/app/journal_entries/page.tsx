// Next.js App Router page generated from the OpenAPI contract.
import { apiGet } from '@/lib/api';

export const dynamic = 'force-dynamic';

type Row = Record<string, unknown>;

export default async function JournalEntriesPage() {
  let rows: Row[] = [];
  let error: string | null = null;
  try {
    rows = await apiGet<Row[]>('/api/v1/journal_entries');
  } catch (err) {
    error = err instanceof Error ? err.message : 'request failed';
  }

  return (
    <main className="mx-auto max-w-4xl p-8">
      <h1 className="text-2xl font-semibold">Journal Entries</h1>
      <p className="mt-2 text-sm text-gray-500">سامانه یکپارچه Erp سازمانی شامل حسابداری مالیاتی، ترازنامه، — generated by the Roxira swarm.</p>
      {error ? (
        <p className="mt-6 rounded bg-red-50 p-4 text-red-700">{error}</p>
      ) : rows.length === 0 ? (
        <p className="mt-6 text-gray-500">No records yet.</p>
      ) : (
        <table className="mt-6 w-full border-collapse text-left text-sm">
          <thead>
            <tr>
              {Object.keys(rows[0]).map((key) => (
                <th key={key} className="border-b py-2 font-medium">{key}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row, index) => (
              <tr key={index}>
                {Object.values(row).map((value, cell) => (
                  <td key={cell} className="border-b py-2">{String(value)}</td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </main>
  );
}
